CREATE TABLE staff (
  staff_id INTEGER PRIMARY KEY,
  name     TEXT NOT NULL,
  role     TEXT NOT NULL
);

CREATE TABLE rooms (
  room_no TEXT PRIMARY KEY,
  floor   INTEGER NOT NULL,
  status  TEXT NOT NULL           -- occupied / vacant
);

CREATE TABLE residents (
  resident_id   INTEGER PRIMARY KEY,
  name          TEXT,
  room_no       TEXT REFERENCES rooms(room_no),
  moved_in_on   TEXT,
  phone         TEXT,
  registered_by INTEGER REFERENCES staff(staff_id)
);

CREATE TABLE access_log (
  log_id      INTEGER PRIMARY KEY,
  resident_id INTEGER,
  action      TEXT CHECK (action IN ('IN','OUT')),
  logged_at   TEXT
);

CREATE TABLE staff_access_log (
  log_id    INTEGER PRIMARY KEY,
  staff_id  INTEGER REFERENCES staff(staff_id),
  action    TEXT CHECK (action IN ('IN','OUT')),
  logged_at TEXT
);

CREATE TABLE deliveries (
  delivery_id INTEGER PRIMARY KEY,
  room_no     TEXT,
  carrier     TEXT,
  received_at TEXT,
  note        TEXT
);

CREATE TABLE rent_payments (
  payment_id  INTEGER PRIMARY KEY,
  resident_id INTEGER,
  month       TEXT,
  amount      INTEGER,
  payer       TEXT,               -- 本人 / 市補助
  account_no  TEXT
);

CREATE TABLE memos (
  memo_id    INTEGER PRIMARY KEY,
  room_no    TEXT,
  author     TEXT,
  body       TEXT,
  created_at TEXT
);

CREATE TABLE audit_log (
  audit_id    INTEGER PRIMARY KEY,
  table_name  TEXT,
  record_id   INTEGER,
  column_name TEXT,
  old_value   TEXT,
  new_value   TEXT,
  changed_by  INTEGER REFERENCES staff(staff_id),
  changed_at  TEXT
);

CREATE TABLE residents_trash (
  resident_id INTEGER, name TEXT, room_no TEXT, moved_in_on TEXT,
  phone TEXT, registered_by INTEGER, deleted_at TEXT
);

